#!/usr/bin/env python3
"""Keep tests/unit/room_policy_refusal_reasons.txt in step with the HA policy scripts.

The scripts' refusal reasons are generated by scripts/lib/p3b-scripts.js in the
Home Assistant config repo. Run this against a checkout of that repo whenever
its guards change:

    scripts/check-room-policy-refusals.py <ha-config-repo>          # compare
    scripts/check-room-policy-refusals.py <ha-config-repo> --write  # update the pinned list

Exit 0 when the generator's reasons equal the pinned list, 1 when they differ.
The unit test then checks the pinned list against orchestrator.room_policy.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

PINNED = Path(__file__).resolve().parent.parent / "tests" / "unit" / "room_policy_refusal_reasons.txt"
RENDER = (
    "const {renderScripts}=require('./scripts/lib/p3b-scripts');"
    "const r=JSON.parse(require('fs').readFileSync('lib/room-lighting/rooms.json'));"
    "process.stdout.write(JSON.stringify(renderScripts(r.rooms,r.windows)));"
)
REASON = re.compile(r"'reason': '([^']*)'")


def generated_reasons(repo: Path) -> list:
    out = subprocess.run(["node", "-e", RENDER], cwd=repo, capture_output=True, text=True, check=True).stdout
    seen: list = []
    for reason in REASON.findall(json.loads(out)):
        if reason not in seen:
            seen.append(reason)
    return seen


def main(argv: list) -> int:
    args = [a for a in argv if a != "--write"]
    if len(args) != 1:
        print(__doc__)
        return 2
    reasons = generated_reasons(Path(args[0]))
    if not reasons:
        print("no refusal reasons found in the generated scripts")
        return 1
    if "--write" in argv:
        PINNED.write_text("\n".join(reasons) + "\n")
        print(f"wrote {len(reasons)} reasons")
        return 0
    pinned = PINNED.read_text().splitlines()
    if sorted(pinned) == sorted(reasons):
        print(f"{len(reasons)} reasons match")
        return 0
    print("pinned list differs from the generator")
    for reason in sorted(set(reasons) - set(pinned)):
        print(f"  new: {reason}")
    for reason in sorted(set(pinned) - set(reasons)):
        print(f"  gone: {reason}")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
